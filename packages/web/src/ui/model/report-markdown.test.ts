import { afterEach, describe, expect, it } from 'vitest';
import { type DayReport, LOCALES, REPORT_BUCKETS, reportAgent, reportProject } from '@ai-office/shared';
import { setLocale } from '../../i18n';
import { escapeMarkdown, renderReportMarkdown } from './report-markdown';

const at = (hour: number, minute = 0): number => new Date(2026, 9, 21, hour, minute).getTime();

function sampleReport(over: Partial<DayReport> = {}): DayReport {
  const activity = new Array<number>(REPORT_BUCKETS).fill(0);
  const ana = reportAgent({
    agentId: 'claude:s1',
    name: 'Ana',
    firstAt: at(9, 12),
    lastAt: at(17, 40),
    activeMs: 3 * 3_600_000 + 5 * 60_000,
    statusMs: { working: 11_100_000, waiting: 300_000, idle: 900_000 },
    prompts: 6,
    toolCalls: { read: 31, edit: 12, bash: 9 },
    files: [
      { path: 'src/carrinho/Carrinho.tsx', edits: 4, added: 60, removed: 12 },
      { path: 'src/api/pedidos.ts', edits: 2, added: 20, removed: 3 },
    ],
    commands: [{ command: 'npm test', runs: 4 }, { command: 'git status', runs: 1 }],
    tests: [
      { runner: 'vitest', at: at(10), outcome: 'passed', passed: 40 },
      { runner: 'vitest', at: at(11), outcome: 'failed', passed: 38, failed: 2 },
      { runner: 'vitest', at: at(12), outcome: 'passed', passed: 40 },
    ],
    commits: [{ hash: 'abc1234', subject: 'feat: cupom [novo] *importante*', branch: 'main', at: at(12), source: 'transcript' }],
    tasks: [{ title: 'Criar a rota de cobrança', at: at(10) }, { title: '# Testar o checkout', at: at(11) }],
    subagents: { count: 2, types: ['Explore'] },
    usage: { tokens: 1_200_000, costUSD: 14.2 },
    requests: ['Adicionar cupom ao carrinho'],
    activity,
  });
  const bruno = reportAgent({ agentId: 'claude:s2', name: 'Bruno', sessionId: 's2', firstAt: at(14), lastAt: at(15), activeMs: 1_800_000, prompts: 1, toolCalls: { read: 2 }, usage: { tokens: 50_000, costUSD: 0.6 } });
  return { date: '2026-10-21', generatedAt: at(18), account: 'all', includeRequests: false, projects: [reportProject([ana, bruno], { id: '/work/loja-online', name: 'loja-online' })], ...over };
}

