describe('escapeMarkdown', () => {
  it('keeps session text from becoming Markdown structure', () => {
    expect(escapeMarkdown('# título\n**forte** [link](x) <b> a|b `c`')).toBe('\\# título \\*\\*forte\\*\\* \\[link\\](x) \\<b\\> a\\|b \\`c\\`');
    expect(escapeMarkdown('- item')).toBe('\\- item');
  });
});
