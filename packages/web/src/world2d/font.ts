/** Strip diacritics and upper-case a string for the 3x5 font. */
export function foldText(text: string): string {
  return text.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
}

export const GLYPH_W = 3;
export const GLYPH_H = 5;

/** Width in px of `text` at scale 1 (3 px per glyph + 1 px gap). */
export function textWidth(text: string): number {
  const n = foldText(text).length;
  return n === 0 ? 0 : n * (GLYPH_W + 1) - 1;
}

type Painter = { fillStyle: string | CanvasGradient | CanvasPattern; fillRect(x: number, y: number, w: number, h: number): void };

/** Draw `text` with its top-left at (x, y). */
export function drawPixelText(ctx: Painter, text: string, x: number, y: number, color: string, scale = 1): void {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of foldText(text)) {
    const glyph = GLYPHS[ch];
    if (glyph) {
      for (let row = 0; row < GLYPH_H; row++) {
        for (let col = 0; col < GLYPH_W; col++) {
          if (glyph[row][col] === '#') ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
        }
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}
